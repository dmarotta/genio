import { beforeEach, expect, it, vi } from 'vitest'
const probes = vi.hoisted(() => ({
  claude: vi.fn(), codex: vi.fn(), gemini: vi.fn(), opencode: vi.fn(), key: vi.fn(), accounts: vi.fn()
}))
vi.mock('../src/main/accounts', () => ({ listAccounts: probes.accounts, scrubDetail: (s: string) => s }))
vi.mock('../src/main/secrets', () => ({ getSecret: probes.key }))
vi.mock('../src/main/model-discovery', () => ({ claudeModels: probes.claude, codexModels: probes.codex, geminiModels: probes.gemini, opencodeModels: probes.opencode }))
beforeEach(() => {
  vi.resetModules(); vi.clearAllMocks()
  probes.accounts.mockResolvedValue(['claude', 'codex', 'gemini', 'opencode'].map(tool => ({ tool, installed: true, state: tool === 'gemini' ? 'unknown' : 'logged-in', detail: 'ChatGPT' })))
  probes.key.mockReturnValue(undefined)
  probes.claude.mockResolvedValue([{ value: 'opus', resolvedModel: 'claude-opus' }])
  probes.codex.mockResolvedValue([{ id: 'gpt' }])
  probes.gemini.mockRejectedValue(new Error('Gemini API key is missing or not configured'))
  probes.opencode.mockResolvedValue([{ id: 'opencode/free' }])
})
it('reports Gemini Sign in and anonymous OpenCode, and never probes OpenRouter without a stored key', async () => {
  const { modelCatalogue } = await import('../src/main/model-catalogue')
  const c = await modelCatalogue('data')
  expect(c.routes.find(r => r.runtime === 'gemini')).toMatchObject({ state: 'sign-in-needed', models: [], lastResult: 'error' })
  expect(c.routes.find(r => r.provider === 'OpenCode')).toMatchObject({ state: 'free-no-login' })
  expect(c.routes.find(r => r.provider === 'OpenRouter')).toMatchObject({ state: 'sign-in-needed', models: [] })
  expect(probes.opencode).toHaveBeenCalledTimes(1)
})
it('coalesces refreshes, preserves timestamped stale results after failure and refreshes after invalidation', async () => {
  const { modelCatalogue, invalidateModelCatalogue } = await import('../src/main/model-catalogue')
  const first = await modelCatalogue('data')
  await modelCatalogue('data')
  expect(probes.claude).toHaveBeenCalledTimes(1)
  probes.claude.mockRejectedValue(new Error('Offline'))
  invalidateModelCatalogue()
  const [second, same] = await Promise.all([modelCatalogue('data'), modelCatalogue('data')])
  expect(second).toEqual(same)
  expect(probes.claude).toHaveBeenCalledTimes(2)
  expect(second.routes[0]).toMatchObject({ models: first.routes[0].models, sourceAt: first.routes[0].sourceAt, stale: true, lastResult: 'error', state: 'unavailable' })
})
it('expires the catalogue at a bounded TTL', async () => {
  const { modelCatalogue, CATALOGUE_TTL } = await import('../src/main/model-catalogue')
  const now = Date.now()
  const clock = vi.spyOn(Date, 'now').mockReturnValue(now)
  try {
    await modelCatalogue('data')
    clock.mockReturnValue(now + CATALOGUE_TTL + 1)
    await modelCatalogue('data')
    expect(probes.claude).toHaveBeenCalledTimes(2)
  } finally { clock.mockRestore() }
})
it('rechecks credentials when a login completes during an outstanding discovery', async () => {
  const { modelCatalogue, invalidateModelCatalogue } = await import('../src/main/model-catalogue')
  let release!: (rows: { value: string }[]) => void
  probes.claude.mockReturnValueOnce(new Promise(resolve => { release = resolve }))
  const old = modelCatalogue('data')
  await Promise.resolve()
  invalidateModelCatalogue()
  const fresh = modelCatalogue('data', true)
  release([{ value: 'old' }])
  expect((await old).routes[0].stale).toBe(true)
  expect((await fresh).routes[0]).toMatchObject({ stale: false, models: [{ id: 'claude-opus' }] })
  expect(probes.claude).toHaveBeenCalledTimes(2)
})

it('returns the static Claude list on first discovery failure and retries quietly', async () => {
  const { modelCatalogue } = await import('../src/main/model-catalogue')
  probes.claude.mockRejectedValue(new Error('offline'))
  const first = await modelCatalogue('data')
  expect(first.routes[0].models.map(m => m.id)).toContain('claude-sonnet-5-5')
  expect(first.routes[0].state).toBe('unavailable')
  probes.accounts.mockRejectedValue(new Error('offline'))
  expect(await modelCatalogue('data', true)).toEqual(first)
})
