#!/usr/bin/env node
/**
 * Generates THIRD_PARTY_NOTICES.md: the runtime dependencies (package-lock.json entries that are not dev-only) with
 * the license in each installed package.json, and a flag on any license that is not plainly permissive.
 * Usage: node scripts/third-party-notices.mjs [--check]   (run after `npm ci`). Standard library only.
 * --check prints the flagged packages and exits 1 when there are any, without writing the file.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const lock = JSON.parse(fs.readFileSync(path.join(root, 'package-lock.json'), 'utf8'))

const PERMISSIVE = /^(MIT|MIT-0|ISC|BSD-2-Clause|BSD-3-Clause|0BSD|Apache-2\.0|BlueOak-1\.0\.0|Unlicense|CC0-1\.0|Python-2\.0|CC-BY-4\.0|OFL-1\.1|Zlib)$/

function licenseOf(pkgJson, lockEntry) {
  const l = pkgJson?.license ?? lockEntry.license
  if (typeof l === 'string') return l
  if (l && typeof l === 'object' && l.type) return l.type
  if (Array.isArray(pkgJson?.licenses)) return pkgJson.licenses.map((x) => x.type).join(' OR ')
  return 'UNKNOWN'
}

/** An SPDX expression is fine when every AND-term has at least one permissive OR-choice. */
function permissive(expr) {
  const terms = expr.replace(/[()]/g, '').split(/\s+AND\s+/)
  return terms.every((t) => t.split(/\s+OR\s+/).some((id) => PERMISSIVE.test(id.trim())))
}

const rows = []
for (const [key, entry] of Object.entries(lock.packages ?? {})) {
  if (!key || entry.dev || entry.devOptional) continue
  const dir = path.join(root, key)
  let pkg = null
  try { pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8')) } catch { /* not installed (optional platform build) */ }
  const name = pkg?.name ?? key.replace(/^.*node_modules\//, '')
  const license = licenseOf(pkg, entry)
  rows.push({ name, version: pkg?.version ?? entry.version, license, installed: !!pkg, optional: !!entry.optional })
}
rows.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))
const flagged = rows.filter((r) => !permissive(r.license))

if (process.argv.includes('--check')) {
  for (const r of flagged) console.log(`${r.name}@${r.version}: ${r.license}`)
  process.exit(flagged.length ? 1 : 0)
}

const rootPkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'))
const out = []
out.push('# Third-party notices', '')
out.push(`Genio itself is released under the [MIT License](LICENSE). It is built on the open-source packages below and`)
out.push(`can download optional components at your request. Generated by \`scripts/third-party-notices.mjs\` from`)
out.push(`\`package-lock.json\` and the installed packages; do not edit by hand.`, '')
out.push('## Optional components Genio downloads on request', '')
out.push(`These are not part of this repository and are fetched only after you click Download (see [docs/voice.md](docs/voice.md)).`)
out.push(`Each is verified against a pinned SHA-256 and stored in Genio's own data folder.`, '')
out.push('| Component | Used for | License |', '|---|---|---|')
out.push('| whisper.cpp v1.8.2 with OpenBLAS | Speech recognition for push-to-talk | MIT; OpenBLAS BSD-3-Clause |')
out.push('| Whisper `small.en` model (quantized) | Speech recognition for push-to-talk | MIT |')
out.push('| sherpa-onnx 1.13.8 Node addon (`sherpa-onnx-win-x64`) | Runs the natural voice | Apache-2.0 and MIT; includes espeak-ng under GPL-3.0-or-later |')
out.push('| Kokoro en v0.19 model | The natural voice | Apache-2.0 (weights); espeak-ng phoneme data is GPL-3.0-or-later |', '')
out.push(`**The natural voice's runtime download includes GPL components.** The sherpa-onnx addon has espeak-ng built in, and`)
out.push(`espeak-ng is licensed GPL-3.0-or-later. Those components are not part of this repository's MIT code and Genio does`)
out.push(`not distribute them: you download them from their publishers after saying yes, and they run in a separate helper`)
out.push(`process. Anyone who bundles the addon or model with Genio has to meet the GPL-3.0 for that part. The reasoning is in`)
out.push(`[docs/voice.md](docs/voice.md).`, '')
out.push('## Not covered by an open-source license', '')
out.push(`Genio signs you in to, and runs, tools you install yourself under their own terms: Claude Code, Codex, Git, the`)
out.push(`GitHub CLI, Blender and Unity. They are not included in Genio.`, '')
out.push('## Runtime dependencies', '')
out.push(`${rows.length} packages (direct and transitive, excluding development-only tools such as the build chain and test runner).`)
out.push(`Packages marked "optional" are platform-specific builds installed only where they apply.`, '')
if (flagged.length) {
  out.push('### Licenses to review', '')
  out.push('Not on the list of plainly permissive licenses (MIT, ISC, BSD, Apache-2.0 and similar):', '')
  for (const r of flagged) out.push(`- \`${r.name}@${r.version}\`: ${r.license}`)
  if (flagged.some((r) => r.name.startsWith('@anthropic-ai/claude-agent-sdk'))) {
    out.push(`The Claude Agent SDK (\`@anthropic-ai/claude-agent-sdk\` and its platform builds) is proprietary: "© Anthropic PBC. All`)
    out.push(`rights reserved. Use is subject to the Legal Agreements" at https://code.claude.com/docs/en/legal-and-compliance.`)
    out.push(`It is a dependency Genio installs from npm, not code in this repository, and is not covered by Genio's MIT license.`, '')
  }
  out.push('')
}
out.push('### All packages', '', '| Package | Version | License |', '|---|---|---|')
for (const r of rows) out.push(`| ${r.name}${r.optional ? ' (optional)' : ''} | ${r.version} | ${r.license.replace(/\|/g, '/')}${r.installed ? '' : ' (not installed here; from lockfile)'} |`)
out.push('')
fs.writeFileSync(path.join(root, 'THIRD_PARTY_NOTICES.md'), out.join('\n'), 'utf8')
console.log(`THIRD_PARTY_NOTICES.md: ${rows.length} packages, ${flagged.length} to review (${rootPkg.name} ${rootPkg.version})`)
